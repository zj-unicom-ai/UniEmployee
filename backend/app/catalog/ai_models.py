def resolve_runtime_model(model_str):
    """供 compiler._init_model 调用：按 model_str 查 DB 取 api_key/api_domain。

    解析顺序：
    1. strip "openai:" 前缀 → 得到 base_model 名 → 查 DB 精确匹配
    2. 未命中 → 查 DB 默认模型（default_model=1）
    3. 都没有 → 返回 None（回退到环境变量）

    返回 dict: {base_model, api_key, api_domain, protocol} 或 None。
    """
    if not model_str:
        # 没指定模型名，直接看默认
        d = get_default_model()
        return _runtime_cfg(d) if d else None
    base = model_str.split(":", 1)[1] if ":" in model_str else model_str
    con = _conn()
    r = con.execute(
        "SELECT * FROM ai_models WHERE base_model=? AND status=1 LIMIT 1",
        (base,)).fetchone()
    con.close()
    if r:
        return _runtime_cfg(_row(r))
    # 精确未命中 → 默认模型
    d = get_default_model()
    return _runtime_cfg(d) if d else None


def _runtime_cfg(row):
    if not row:
        return None
    return {
        "base_model": row["base_model"],
        "api_key": row.get("api_key") or "",
        "api_domain": row["api_domain"],
        "protocol": row.get("protocol", 1),
    }


def _encode_config(config_list):
    if not config_list:
        return None
    if isinstance(config_list, str):
        return config_list
    try:
        return json.dumps(config_list, ensure_ascii=False)
    except Exception:
        return None


def seed_default_model_if_empty():
    """表空时从环境变量播种一条默认模型记录（幂等）。"""
    con = _conn()
    cnt = con.execute("SELECT COUNT(*) AS c FROM ai_models").fetchone()["c"]
    if cnt > 0:
        con.close()
        return
    model_name = os.environ.get("MODEL_NAME", "")
    if not model_name:
        con.close()
        return
    base = model_name.split(":", 1)[1] if ":" in model_name else model_name
    api_domain = os.environ.get("OPENAI_BASE_URL", "")
    api_key = os.environ.get("OPENAI_API_KEY", "")
    if not api_domain:
        con.close()
        return
    dblayer.insert_returning_id(
        con,
        "INSERT INTO ai_models(name, supplier, model_type, base_model, "
        "default_model, api_key, api_domain, protocol, config, status, created_at) "
        "VALUES(?,?,?,?,?,?,?,?,?,?,?)",
        ("默认模型", 1, 1, base, 1, api_key, api_domain, 1, None, 1,
         time.strftime("%Y-%m-%d %H:%M:%S")))
    con.commit()
    con.close()
