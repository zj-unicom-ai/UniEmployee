def init_tables(con=None):
    """幂等建表；catalog.init() 传入已建好基础表的连接复用。"""
    own = con is None
    if own:
        con = _conn()
    con.executescript(f"""
    CREATE TABLE IF NOT EXISTS ai_models(
      id {_ID},
      name TEXT NOT NULL,
      supplier INTEGER NOT NULL,
      model_type INTEGER NOT NULL,
      base_model TEXT NOT NULL,
      default_model INTEGER DEFAULT 0,
      api_key TEXT,
      api_domain TEXT NOT NULL,
      protocol INTEGER DEFAULT 1,
      config TEXT,
      status INTEGER DEFAULT 1,
      created_at TEXT);
    CREATE INDEX IF NOT EXISTS idx_ai_models_default ON ai_models(default_model);
    CREATE INDEX IF NOT EXISTS idx_ai_models_base ON ai_models(base_model);
    """)
    con.commit()
    if own:
        con.close()


