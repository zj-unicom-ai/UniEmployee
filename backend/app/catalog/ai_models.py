def _row(r):
    if r is None:
        return None
    d = dict(r)
    if d.get("config"):
        try:
            d["config_list"] = json.loads(d["config"])
        except Exception:
            d["config_list"] = []
    else:
        d["config_list"] = []
    return d


def list_models(keyword="", model_type=None):
    """列表查询，支持按名称/base_model 关键词和模型类型筛选。"""
    where, params = [], []
    if keyword:
        where.append("(name LIKE ? OR base_model LIKE ?)")
        params += [f"%{keyword}%", f"%{keyword}%"]
    if model_type:
        where.append("model_type=?")
        params.append(model_type)
    cond = (" WHERE " + " AND ".join(where)) if where else ""
    con = _conn()
    rows = con.execute(
        f"SELECT * FROM ai_models{cond} ORDER BY default_model DESC, id DESC",
        params).fetchall()
    con.close()
    return [_row(r) for r in rows]


def get_model(model_id):
    con = _conn()
    r = con.execute("SELECT * FROM ai_models WHERE id=?", (model_id,)).fetchone()
    con.close()
    return _row(r)


def create_model(data):
    con = _conn()
    mid = dblayer.insert_returning_id(
        con,
        "INSERT INTO ai_models(name, supplier, model_type, base_model, "
        "default_model, api_key, api_domain, protocol, config, status, created_at) "
        "VALUES(?,?,?,?,?,?,?,?,?,?,?)",
        (data["name"], data.get("supplier", 1), data.get("model_type", 1),
         data["base_model"], 0, data.get("api_key", ""),
         data["api_domain"], data.get("protocol", 1),
         _encode_config(data.get("config_list")), 1,
         time.strftime("%Y-%m-%d %H:%M:%S")))
    con.commit()
    con.close()
    return mid


def update_model(model_id, data):
    before = get_model(model_id)
    if not before:
        return False
    con = _conn()
    con.execute(
        "UPDATE ai_models SET name=?, supplier=?, model_type=?, base_model=?, "
        "api_key=?, api_domain=?, protocol=?, config=? WHERE id=?",
        (data.get("name", before["name"]),
         data.get("supplier", before["supplier"]),
         data.get("model_type", before["model_type"]),
         data.get("base_model", before["base_model"]),
         data.get("api_key", before["api_key"]),
         data.get("api_domain", before["api_domain"]),
         data.get("protocol", before["protocol"]),
         _encode_config(data.get("config_list")),
         model_id))
    con.commit()
    con.close()
    return True


def delete_model(model_id):
    con = _conn()
    cur = con.execute("DELETE FROM ai_models WHERE id=?", (model_id,))
    con.commit()
    con.close()
    return cur.rowcount > 0


def set_default_model(model_id):
    """设为默认：先清所有 default_model=0，再置目标为 1。"""
    con = _conn()
    row = con.execute("SELECT 1 FROM ai_models WHERE id=?", (model_id,)).fetchone()
    if not row:
        con.close()
        return False
    con.execute("UPDATE ai_models SET default_model=0")
    con.execute("UPDATE ai_models SET default_model=1 WHERE id=?", (model_id,))
    con.commit()
    con.close()
    return True


def get_default_model():
    con = _conn()
    r = con.execute(
        "SELECT * FROM ai_models WHERE default_model=1 AND status=1 LIMIT 1"
    ).fetchone()
    con.close()
    return _row(r)


