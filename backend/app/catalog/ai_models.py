"""AI 模型配置管理（挂 catalog 库）。

表结构参考 Aix-DB 的 t_ai_model：记录供应方 / 模型类型 / base_model /
api_key / api_domain 等信息，运行时由 compiler._init_model 通过
resolve_runtime_model() 查表注入，替代写死的环境变量。
"""
